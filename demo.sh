#!/usr/bin/env bash
# Практическая проверка задания Дня 11: что попадает в каждый слой памяти и как
# это влияет на ответы.
#
# Имена переменных латиницей: bash не поддерживает кириллицу в идентификаторах
# и молча превращает $ИМЯ в обычный текст.
#
# Запуск:  bash demo.sh  [путь-к-python]
set -u
PY="${1:-python3}"
MEM="demo-memory"

step() { printf '\n\n=== %s ===\n' "$1"; }

rm -rf "$MEM"

step "1. ГДЕ ЧТО ЛЕЖИТ: три слоя — три хранилища"
"$PY" cli.py --память-в "$MEM" --файлы

step "2. НАПОЛНЕНИЕ СЛОЁВ СРАЗУ ПОСЛЕ ЗАПУСКА"
"$PY" cli.py --память-в "$MEM" --память

step "3. ПРОФИЛЬ И ИНВАРИАНТЫ: что проверяется кодом, а что моделью"
"$PY" cli.py --память-в "$MEM" --профиль

step "4. ВОПРОС С РАЗБОРОМ ПРОМПТА: видно, что из какого слоя ушло"
"$PY" cli.py --память-в "$MEM" --маршрутизатор выкл --трейс \
  "Куда в новой системе переедет таблица gissys.organization?"

step "5. ТОТ ЖЕ ВОПРОС БЕЗ ДОЛГОВРЕМЕННОЙ ПАМЯТИ"
"$PY" cli.py --память-в "$MEM" --маршрутизатор выкл --слои кратко,рабочая --трейс \
  "Куда в новой системе переедет таблица gissys.organization?"

step "6. ЗАДАЧА: стадии меняет код, а не уверенность модели"
"$PY" cli.py --память-в "$MEM" --новая-задача перенос-моделей \
  --название "схема gissys в модели GeoDjango"
"$PY" cli.py --память-в "$MEM" --задача перенос-моделей --стадия done 2>&1 | tail -2
"$PY" cli.py --память-в "$MEM" --задача перенос-моделей --стадия execution
"$PY" cli.py --память-в "$MEM" --задача перенос-моделей \
  --шаг "таблиц=37, из них 12 с геометрией"

step "7. ЗАВЕРШЕНИЕ ЗАДАЧИ: рабочая память сворачивается в решение"
"$PY" cli.py --память-в "$MEM" --задача перенос-моделей --стадия validation
"$PY" cli.py --память-в "$MEM" --задача перенос-моделей --завершить

step "8. МАРШРУТИЗАТОР: свободная реплика разбирается дешёвой моделью"
"$PY" cli.py --память-в "$MEM" "У нас PostGIS 3.6, а не 3.4 — учитывай это" >/dev/null
"$PY" cli.py --память-в "$MEM" --журнал

step "9. ЧТО НАКОПИЛОСЬ В СЛОЯХ К КОНЦУ"
"$PY" cli.py --память-в "$MEM" --память

printf '\n\nГотово. Память прогона осталась в «%s» — её можно посмотреть глазами.\n' "$MEM"
